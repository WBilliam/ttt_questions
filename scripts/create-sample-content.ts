const root = process.cwd();
const workbookPath = path.join(root, "content/demo/questions.xlsx");
await mkdir(path.dirname(workbookPath), { recursive: true });
const workbook = new ExcelJS.Workbook();
workbook.creator = "Practice Quiz";
const sheet = workbook.addWorksheet("Questions", { views: [{ state: "frozen", ySplit: 1 }] });
sheet.addRow(headers);
rows.forEach((row) => sheet.addRow(row));
sheet.getRow(1).font = { bold: true, color: { argb: "FFFFFFFF" } };
sheet.getRow(1).fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF173F35" } };
sheet.getRow(1).alignment = { vertical: "middle", horizontal: "center" };
sheet.columns = headers.map((header) => ({
  key: header,
  width: ["question", "explanation"].includes(header)
    ? 46
    : ["category", "image_alt"].includes(header)
      ? 30
      : 20
}));
sheet.eachRow((row, number) => {
  row.alignment = { vertical: "top", wrapText: number > 1 };
});
sheet.autoFilter = { from: "A1", to: "L13" };
await workbook.xlsx.writeFile(workbookPath);

